/// Full Security Scan Results Screen
///
/// VIVA ARCHITECTURE EXPLANATION:
/// 1. Visual Speedometer: Dynamic custom painter gauge interpolates 0-100 score.
/// 2. Haptic Signals: Trigger hardware haptics (medium impact on scan completion,
///    heavy impact on high-risk detections) to assist cognitive triage.
/// 3. Modular Actions: Provides direct deep navigation to the recursive dependency
///    graph, as well as native file export via Android share sheet for PDF reports.
class ResultsScreen extends ConsumerStatefulWidget {
  const ResultsScreen({super.key});

  @override
  ConsumerState<ResultsScreen> createState() => _ResultsScreenState();
}

class _ResultsScreenState extends ConsumerState<ResultsScreen> {
  bool _exportingPdf = false;

  @override
  void initState() {
    super.initState();
    // Fire haptic feedback on scan completion
    WidgetsBinding.instance.addPostFrameCallback((_) {
      final result = ref.read(lastScanResultProvider);
      if (result != null) {
        final level = RiskLevel.fromApi(result.riskLabel);
        if (level == RiskLevel.highRisk || result.riskScore >= 70) {
          HapticFeedback.heavyImpact();
        } else {
          HapticFeedback.mediumImpact();
        }
      }
    });
  }

  Future<void> _exportPdfReport(String? scanId, String packageName) async {
    if (scanId == null || scanId.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('No scan ID associated with this session.')),
      );
      return;
    }

    setState(() => _exportingPdf = true);
    try {
      final repo = ref.read(scanRepositoryProvider);
      final res = await repo.downloadPdfReport(scanId);

      if (res is ApiSuccess<List<int>>) {
        final tempDir = await getTemporaryDirectory();
        final file = File('${tempDir.path}/packguard_report_${packageName}_$scanId.pdf');
        await file.writeAsBytes(res.data);

        await Share.shareXFiles(
          [XFile(file.path, mimeType: 'application/pdf')],
          subject: 'PackGuard Security Report — $packageName',
          text: 'Security audit report for $packageName generated by PackGuard.',
        );
      } else if (res is ApiFailure<List<int>>) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Report export failed: ${res.message}')),
          );
        }
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Error exporting report: $e')),
        );
      }
    } finally {
      if (mounted) setState(() => _exportingPdf = false);
    }
  }

