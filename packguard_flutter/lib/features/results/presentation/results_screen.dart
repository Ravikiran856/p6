  List<Widget> _buildGroupedTaxonomyFindings(List<ScanFinding> findings) {
    final Map<String, List<ScanFinding>> grouped = {};
    for (final f in findings) {
      grouped.putIfAbsent(f.category, () => []).add(f);
    }

    final List<Widget> widgets = [];
    int globalIndex = 0;

    for (final entry in grouped.entries) {
      final category = entry.key;
      final items = entry.value;
      final categoryColor = _getTaxonomyColor(category);
      final categoryIcon = _getTaxonomyIcon(category);

      widgets.add(
        Padding(
          padding: const EdgeInsets.only(top: 10, bottom: 8),
          child: Row(
            children: [
              Container(
                padding: const EdgeInsets.all(5),
                decoration: BoxDecoration(
                  color: categoryColor.withOpacity(0.14),
                  borderRadius: BorderRadius.circular(6),
                ),
                child: Icon(categoryIcon, size: 14, color: categoryColor),
              ),
              const SizedBox(width: 8),
              Text(
                category.toUpperCase(),
                style: TextStyle(
                  color: categoryColor,
                  fontWeight: FontWeight.w800,
                  fontSize: 11,
                  letterSpacing: 0.8,
                ),
              ),
              const SizedBox(width: 6),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 1.5),
                decoration: BoxDecoration(
                  color: AppColors.surfaceElevated,
                  borderRadius: BorderRadius.circular(8),
                ),
                child: Text(
                  '${items.length}',
                  style: const TextStyle(color: AppColors.textMuted, fontSize: 10, fontWeight: FontWeight.bold),
                ),
              ),
            ],
          ),
        ),
      );

      for (final finding in items) {
        widgets.add(
          ExpandableFindingCard(
            finding: finding,
            index: globalIndex++,
          ),
        );
      }
    }

    return widgets;
  }

  Color _getTaxonomyColor(String category) {
    switch (category) {
      case 'Execution':
      case 'Persistence':
      case 'Defense Evasion':
      case 'Command & Control':
        return AppColors.highRisk;
      case 'Exfiltration':
      case 'Discovery':
      case 'Metadata Manipulation':
      default:
        return AppColors.suspicious;
    }
  }

  IconData _getTaxonomyIcon(String category) {
    switch (category) {
      case 'Execution':
        return Icons.terminal;
      case 'Persistence':
        return Icons.extension;
      case 'Defense Evasion':
        return Icons.enhanced_encryption;
      case 'Exfiltration':
        return Icons.wifi_tethering;
      case 'Discovery':
        return Icons.search;
      case 'Command & Control':
        return Icons.hub_outlined;
      case 'Metadata Manipulation':
        return Icons.spellcheck;
      default:
        return Icons.security;
    }
  }
